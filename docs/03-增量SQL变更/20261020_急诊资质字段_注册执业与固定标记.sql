-- =====================================================================
-- 20261020 急诊值班资质字段：员工档案加「本机构注册执业 / 固定医师」标记
-- ---------------------------------------------------------------------
-- 依据：
--   1) 《急诊科建设与管理指南（试行）》卫医政发〔2009〕50号 第十六条：
--      急诊医师应具有 3 年以上临床经验，固定急诊医师应不低于在岗急诊医师的 75%。
--   2) 《医疗质量安全核心制度要点》国卫医发〔2018〕8号：
--      当值医务人员中必须有本机构执业的人员，非本机构执业人员不得单独值班。
--
-- 落地说明：
--   is_registered  NULL=未登记（排班校验放行，避免档案未维护就误伤排班）；
--                  0=否（排急诊夜班被后端拦截）；1=是。
--   is_fixed       NULL=未登记；0=轮转；1=固定（仅用于固定急诊医师占比统计/评审上报）。
--   校验口径：急诊科室单元（19580047/48/49/51）+ 医生岗位 + 夜班班次 + 值班人 is_registered=0 → 拦截。
--
-- ⚠️ 执行后请到员工档案维护急诊科医生的 is_registered=1（本院注册执业）与 is_fixed 标记；
--    未维护（NULL）的医生不会拦排班，但固定占比统计口径会偏低。
-- =====================================================================

ALTER TABLE sys_employee
    ADD COLUMN is_registered tinyint NULL COMMENT '本机构注册执业（0-否 1-是 NULL-未登记；非本机构注册执业不得单独值班）' AFTER is_expert,
    ADD COLUMN is_fixed      tinyint NULL COMMENT '是否固定医师（0-轮转 1-固定 NULL-未登记；急诊固定医师≥75%评审口径）' AFTER is_registered;

