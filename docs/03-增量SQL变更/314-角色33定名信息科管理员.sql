-- ============================================================================
-- 314-角色33定名「信息科管理员」（sql313 已执行库的改名增量）
-- ============================================================================
-- 背景：sql313 新建角色 33 时定名「信息科」，评审后改为「信息科管理员」——
--   与「系统管理员」构词一致（角色描述干什么，不直接占科室名），
--   也为信息科后续增设其他岗位（只读/审计）留出命名空间。
--   role_code(10043) / 授权（29621+29623）/ 绑岗（蒋俊杰）均不变，仅改名。
--
-- 适用口径：
--   · 已执行过 313 旧版（role_name='信息科'）的库：本脚本完成改名，1 行生效；
--   · 全新铺底 / 执行的是改名后的 313：本脚本 0 行生效，幂等无害。
--
-- 幂等：WHERE role_name='信息科' 条件兜底，重复执行影响 0 行。
-- ⚠ 执行后清权限/身份缓存（角色名会进登录身份与切岗下拉展示）：
--     redis-cli --scan --pattern 'his:perm:role:*' | xargs redis-cli DEL
--     redis-cli --scan --pattern 'his:user:identity:*' | xargs redis-cli DEL
-- 回滚：UPDATE sys_role SET role_name='信息科' WHERE id=33;
-- ============================================================================

UPDATE sys_role
SET role_name = '信息科管理员',
    update_by = 'sql314',
    update_time = NOW()
WHERE id = 33 AND role_name = '信息科';

-- ---------------- 回查（期望一行：33 / 10043 / 信息科管理员） ----------------
SELECT id, role_code, role_name, status FROM sys_role WHERE id = 33;
