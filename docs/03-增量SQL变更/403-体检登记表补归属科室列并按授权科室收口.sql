-- 403 体检登记表补归属科室列，列表/详情按岗位授权科室行级收口
-- 日期：2026-11-27
-- 依据：107 文档 §5.4；厂商按岗位×科室隐私隔离（前台只见本中心客户）。
-- 背景：体检登记列表后端原无任何科室/登记人条件，持菜单即可看全院体检登记
--       （姓名、电话、套餐、金额、总检结论），存在跨中心信息泄露面。
-- ① biz_checkup_record 补 dept_id（登记人当前岗位科室）+ idx_dept 索引
-- ② 后端登记落科室；recordPage 受限角色 IN 授权科室；详情/结果/总检/开始/删除走科室门禁
-- 存量：8 条 admin 测试数据无科室归属，dept_id 留 NULL（受限角色不可见、全院角色可见）；
--       不臆造归属。新登记由后端落当前岗位科室。
-- 回滚：见 403-回滚.sql
-- ============================================================

ALTER TABLE `biz_checkup_record`
  ADD COLUMN `dept_id` bigint NULL COMMENT '归属科室ID（登记人当前岗位科室；列表按授权科室收口）' AFTER `record_no`,
  ADD KEY `idx_dept` (`dept_id`);
