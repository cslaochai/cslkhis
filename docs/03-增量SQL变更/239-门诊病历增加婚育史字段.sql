-- 门诊病历增加「婚育史」字段（2026-10-22）
-- 背景：医生工作站病史区原有 既往史/个人史/家族史/过敏史 四项，缺「婚育史」——
--   国标入院记录与威海等智慧服务标杆的「一诉五史」都把婚育史单列（主诉/现病史/
--   既往史/个人史/婚育史/家族史），医生开病历时也常要记婚姻与生育情况。
-- 口径：婚育史为**采集项非必填项**（国标《病历书写基本规范》门诊病历不要求婚育史，
--   男性患者无生育内容），DTO/VO 已同步，不加 @NotBlank。
-- 带入规则：复诊时优先取上次病历原文；患者健康档案侧暂无婚育史明细组，
--   档案不带入本字段（与个人史同，只从上次病历带入）。
-- 一次性变更，执行情况见 dev 库验证记录；DDL 基线已同步（01-初始化DDL/08-门诊病历与处方.sql）

