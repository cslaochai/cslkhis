-- 220 · 客服台补两条引导型 FAQ（M2 入口导流）
--
-- 【为什么补这两条】
-- M2 做了报告解读和费用解释，但入口藏在报告详情页 / 缴费页里。
-- 而患者真正会问的是「报告看不懂怎么办」「为什么自付这么多」——
-- 这两句话**不会**出现在报告页或缴费页，它们出现在客服台。
-- 没有这两条，患者问了也只拿到一条通用答复，AI 能力等于没导流。
--
-- 【口径】
-- 沿用 sql/216 的语料纪律：答案里不写死价格 / 报销比例 / 具体时间点，
-- 涉及这些一律「以现场公示为准 / 请咨询窗口」。
-- 这两条是**引导型**（告诉患者去哪点），不是知识型（不解释指标含义）——
-- 指标含义由 sys_lab_plain_item 白话词典负责（sql/218）。
--
-- 【幂等】
-- 按 faq_no 唯一键 ON DUPLICATE KEY UPDATE，可重复执行。
-- =============================================================================

