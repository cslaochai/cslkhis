-- 384 病案科室对应：按上报口径改名
-- 日期：2026-11-26
-- 背景：医保结算清单的入院/出院/诊断科别、卫统与全国医院数据上报的科室代码，
-- 口径是《医疗卫生机构业务科室分类与代码》(CT08.00.002)，代码形如 A03.01；
-- 病案首页本身只有入院/转科/出院科别，没有“诊疗科目”字段。
-- 本页真实用途是「院内科室 → 上报科室代码」对照，故菜单名不再叫“诊疗科目映射”。

UPDATE sys_menu
SET menu_name = '上报科室代码对照',
    remark    = '院内科室 → 医疗卫生机构业务科室分类与代码（CT08.00.002），即病案科室对应；医保结算清单出院科别、卫统上报用，病案首页本身不填此码'
WHERE id = 29626;

