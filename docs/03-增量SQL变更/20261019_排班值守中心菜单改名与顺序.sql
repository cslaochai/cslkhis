-- 20261019 排班中心改名「排班值守中心」+ 子菜单语义统一 + 顺序调整
-- ---------------------------------------------------------------------
-- 背景（来自排班中心菜单命名评审）：
--   排班与值班是两个业务概念：排班 = 日常出勤计划（人×日×班次），
--   值班 = 8 小时工作制之外的值守保障（坐班/听班/留院值班）。
--   原菜单名存在四类问题：
--   ① 值班域术语分裂：一边「总值班排班」一边「值守点位」，看不出同域；
--   ② 「岗位」撞词：「岗位出勤」指人、「岗位人力标准」指标准，像同类；
--   ③ 名不副实：「岗位出勤」主体是全员排班计划，出勤只是对照结果；
--   ④ 配置项与业务项混排，没有按「日常排班 / 配置 / 值守」分组。
-- 决定：
--   - 主菜单 2945「排班中心」→「排班值守中心」，点名两个域；
--   - 岗位出勤 → 员工排班（主体是排班计划，出勤是闭环第3步）；
--   - 岗位人力标准 → 人力配置标准（去「岗位」避免与员工排班撞词）；
--   - 总值班排班 → 全院总值班（值班域术语统一）；
--   - 值守点位 → 值班点位配置（点明是字典配置入口，非业务操作）；
--   - 顺序：排班总览 → 门诊排班 → 护理排班 → 员工排班 →
--     人力配置标准 → 全院总值班 → 值班点位配置（日常排班聚类，
--     配置跟随排班域，值班域收尾）。
-- 范围：
--   - 仅改 sys_menu.menu_name 与 sort_order；不动 permission 字符串
--     （避免后端接口 403）；不动 biz_shift.use_scope 等业务字典。
-- 注意：
--   执行后需清 Redis 权限缓存(his:perm:role:*) 或重启后端；
--   前端路由 meta.title 与相关文案同步修改（同 commit）。
-- =====================================================================

