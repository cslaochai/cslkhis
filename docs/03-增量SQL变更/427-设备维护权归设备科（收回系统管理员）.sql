-- 427 设备台账维护权归设备科（收回系统管理员）
--
-- 背景：设备建档/编辑/停用/维保登记/计量登记共用同一个 upsert 与状态入口，前端按钮码是
--       asset:equipment:add（2125），页面是 902。目前角色 1（系统管理员）与角色 39
--       （设备与供应室管理员）同时持有，设备台账的实际维护动作应由设备科承担，管理员不再代办。
--
-- 做法：只摘 sys_role_menu 里角色 1 对 902 / 2125 / 2126 的授权。
--       菜单行与按钮码本体保留（角色管理页仍可重新勾选），设备科 39 的授权不动（424 已授）。
--
-- 影响：管理员侧栏「物资设备 → 设备管理」入口消失，后端 asset:equipment:* 一律 403；
--       物资耗材(901)/CSSD(903)/医废(904)/耗材字典(2921)/器械包模板(2932) 不受影响。
--
-- 执行后清 Redis：his:perm:role:*（否则要等 10 分钟 TTL 才生效）
-- 回查：SELECT rm.menu_id, r.role_name FROM sys_role_menu rm JOIN sys_role r ON r.id=rm.role_id
--       WHERE rm.menu_id IN (902,2125,2126) ORDER BY rm.menu_id, r.id;
--
-- 回滚：见 427-回滚.sql
-- =====================================================================
SET NAMES utf8mb4;

DELETE rm FROM sys_role_menu rm
WHERE rm.role_id = 1
  AND rm.menu_id IN (902, 2125, 2126);
