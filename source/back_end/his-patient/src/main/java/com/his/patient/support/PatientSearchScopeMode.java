package com.his.patient.support;

/**
 * 全局患者搜索的**取数模式**，由当前登录角色的岗位性质决定（见 {@link PatientSearchScopeResolver}）。
 *
 * <p>为什么要有这个概念：搜索下拉里的「今日就诊 / 全院档案」两组，本质是**门诊岗位**的
 * 工作视角（今天要接谁）。对不做门诊的岗位（病案编码、质控、医保结算、审计、管理员…）
 * 那组数据是噪音：他搜一个人是来查历史档案的，把今日队列顶到最前、还标注「就诊中 · 心内科 · 张医生」，
 * 既误导（他跟这单门诊没关系）又白扫一遍全天候诊队列。
 *
 * <p>关键约束：**置顶和分组是同一份数据的上下两半，不能只管一半**。只把标题藏掉、
 * 后端还在按今日就诊置顶，结果是顶上几个患者没有标题也没有标注、看起来像随机排序。
 * 所以模式在服务端一处决定，同时控制「查不查、排不排、标不标」。
 */
public enum PatientSearchScopeMode {

    /**
     * 门诊岗位：先今日就诊（本人的最前），再全院档案。当前行为保持不变。
     */
    TODAY_FIRST,

    /**
     * 纯档案：不查候诊队列、不参与排序、不回填 todayVisit* 标注。
     *
     * <p>前端因为「只有一组不打标题」自动退化成单列表，不需要按角色各写一套渲染逻辑。
     */
    ARCHIVE_ONLY
}
