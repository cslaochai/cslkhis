package com.his.emr.support;

/**
 * 规则的适用范围。
 *
 * <p><b>这是本引擎最重要的一条防误报设计</b>。
 * 实测住院侧 38 份文书里有 32 份主诉为空 —— 如果据此判定"32 份病历缺主诉"，
 * 那是彻头彻尾的误报：那 32 份是手术记录、会诊记录、转科记录、输血记录与病程记录，
 * <b>它们本来就不需要写主诉</b>（病历书写规范里只有入院记录和门诊病历要求主诉）。
 *
 * <p>所以每条规则必须声明适用范围，引擎按 {@link QcSnapshot#recordType()} 过滤。
 * 把"必填项"当成全局规则，是把质控系统做成噪声源最快的办法。
 */
public enum QcScope {

    /**
     * 仅门诊病历
     */
    OUTPATIENT("仅门诊病历"),

    /**
     * 门诊病历 + 住院入院记录（record_type=1）。
     * 这两者是文书家族里唯一承载"主诉/现病史/既往史/过敏史/诊疗计划"结构化要素的载体。
     */
    OUTPATIENT_AND_ENTRY("门诊病历与住院入院记录"),

    /**
     * 仅住院文书（全部类型）
     */
    INPATIENT("仅住院文书"),

    /**
     * 仅住院非入院记录文书（病程记录 / 手术记录 / 会诊记录 / 转科记录 / 输血记录…）。
     * 这类文书没有结构化要素，靠"正文"承载内容，所以查的是正文而不是主诉。
     */
    INPATIENT_NOTE("仅住院记录类文书"),

    /**
     * 不区分来源与类型：书写医生、性别与诊断矛盾、生命体征越界这类与文书类型无关的检查。
     */
    ALL("全部门诊与住院文书");

    private final String text;

    QcScope(String text) {
        this.text = text;
    }

    public String getText() {
        return text;
    }
}
