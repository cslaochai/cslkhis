-- 218 · 患者端检验项目白话词典（报告解读能力的规则层地基）
--
-- 【这张表解决什么】
-- 患者看报告的真实障碍不是「拿不到数据」—— reportDetail 页已经把
-- 「项目 / 结果 / 参考区间 / 箭头」全列出来了。真正的障碍是看不懂
-- 「HCT 红细胞压积 0.32 ↓」意味着什么。
-- 于是很自然想到让模型来解释。但直接让模型解释有个致命问题：
-- 它会顺着「血红蛋白偏低」顺手补一句「可能是缺铁性贫血，建议补铁」——
-- 这就是**越界诊断 + 越界医嘱**，而这句话没有任何医生背书，会进患者的认知里。
--
-- 所以这一刀的切法是：
--   哪些项异常 / 是不是危急值 / 趋势是升是降  →  代码算（复用 LabAbnormalJudge 等规则）
--   这项查什么 / 偏高偏低通常意味着什么        →  **人工维护的词典**（本表）
--   把这些事实组织成一段通顺的话              →  模型（可选，没有 key 时省略）
--
-- 词典缺失的项目，系统只说「这项不在参考范围内，建议请医生看看」，**绝不猜**。
-- 猜错的代价远大于「没解释」——后者患者会去问医生，前者他会信。
--
-- 【为什么按项目名匹配而不是项目编码】
-- 库里 laboratory_item_code 与 name 是多对多：JY001 同时对应「红细胞」「白细胞」「血红蛋白」，
-- 39 个 name 只有 38 个 (code,name) 组合，编码不可靠。本表以 item_name 精确匹配为唯一键。
--
-- 【红线】
-- 语料由 workspace/_gen_lab_plain_seed.mjs 生成，脚本内置硬断言：
-- 文案里出现「确诊 / 诊断 / 服用 / 剂量 / mg / 片」等诊断性、用药性词汇，
-- 或包含具体数值剂量，脚本直接非零退出、不产出 SQL。
-- 词典是人工维护的，这条闸就是防止维护者（包括 AI）手滑写进医嘱。
-- =============================================================================

CREATE TABLE `sys_lab_plain_item` (
  `id` bigint NOT NULL COMMENT '主键ID',
  `group_name` varchar(32) NOT NULL COMMENT '所属分组（血常规/肝功能/肾功能/血糖/血脂/炎症/凝血/心肌/电解质/尿常规/大便）',
  `item_name` varchar(64) NOT NULL COMMENT '检验项目名称（与 biz_lab_result.laboratory_item_name 精确匹配）',
  `plain_name` varchar(64) NOT NULL COMMENT '白话名（如：血色素、坏胆固醇、心肌损伤指标）',
  `what_is_it` varchar(200) NOT NULL COMMENT '这项查什么（给患者看的一句话，不含诊断/用药）',
  `high_text` varchar(200) NOT NULL COMMENT '结果偏高时的白话说明',
  `low_text` varchar(200) NOT NULL COMMENT '结果偏低时的白话说明',
  `status` tinyint DEFAULT '1' COMMENT '状态（0-停用 1-启用）',
  `sort_order` int DEFAULT '0' COMMENT '排序号',
  -- BaseEntity 自带 remark，实体继承即有；少了这一列 MP 的全表 select 会直接报 Unknown column
  `remark` varchar(500) DEFAULT NULL COMMENT '备注',
  `create_by` varchar(64) DEFAULT NULL COMMENT '创建人',
  `create_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_by` varchar(64) DEFAULT NULL COMMENT '更新人',
  `update_time` datetime DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `del_flag` tinyint DEFAULT '0' COMMENT '删除标志（0-正常 1-删除）',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_item_name` (`item_name`),
  KEY `idx_group_status` (`group_name`, `status`, `del_flag`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='检验项目白话词典（患者端报告解读的规则层地基，人工维护）';

