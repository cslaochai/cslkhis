-- =============================================================================
-- 232 · 患者端影像检查白话词典（patient_imaging_explain 能力的规则层地基）
--
-- 【这张表解决什么】
-- 检查报告（CT/B超/放射/心电）的「描述 / 结论」是放射科医生写给医生看的文本，
-- 患者拿到的是专业术语原文。P1 的决策是「词典改写影像文本只会丢信息」，因此患者端
-- 明确拒绝检查报告解读。P6（G-17）推翻拒绝边界，但换的路径是：
--   这项检查是查什么 / 检查前后的注意  →  **人工维护的词典**（本表，可穷举 → 纪律 9）
--   报告描述/结论的白话串讲            →  模型（开放文本，逐段过 PatientTextGuard）
--   阴阳性 / 是否危急 / 报告状态       →  代码事实（biz_report 列，模型不得改）
-- P1 反对的「用词典改写影像文本」仍然不碰——本表只解释检查本身，不碰报告文本。
--
-- 【匹配口径】
-- 匹配键 item_name 是**关键词**：biz_report.item_name 是自由组合文本
-- （「胸部CT平扫+三维重建」「腹部彩超（肝胆胰脾肾）」），精确匹配必然大面积脱靶。
-- 匹配规则（代码实现）：报告项目名**包含**关键词即命中，多个命中取关键词最长的一条。
--
-- 【红线】
-- 本表语料与 sys_lab_plain_item 同一纪律：文案不得出现诊断性（确诊/诊断为/患有）、
-- 用药性（服用/剂量/mg/片）表述——词典直接面向患者，没有医生复核环节。
-- =============================================================================

CREATE TABLE `sys_imaging_plain_item` (
  `id` bigint NOT NULL COMMENT '主键ID',
  `group_name` varchar(32) NOT NULL COMMENT '所属分组（放射/超声/心电/内镜）',
  `item_name` varchar(64) NOT NULL COMMENT '匹配关键词（报告项目名包含即命中，取最长命中）',
  `plain_name` varchar(64) NOT NULL COMMENT '白话名（如：胸部CT、B超、心电图）',
  `what_it_does` varchar(200) NOT NULL COMMENT '这项检查是查什么的（给患者看的一句话，不含诊断/用药）',
  `notice_text` varchar(200) DEFAULT NULL COMMENT '检查前后的注意事项（白话，可为空）',
  `status` tinyint DEFAULT '1' COMMENT '状态（0-停用 1-启用）',
  `sort_order` int DEFAULT '0' COMMENT '排序号',
  `remark` varchar(500) DEFAULT NULL COMMENT '备注',
  `create_by` varchar(64) DEFAULT NULL COMMENT '创建人',
  `create_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_by` varchar(64) DEFAULT NULL COMMENT '更新人',
  `update_time` datetime DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `del_flag` tinyint DEFAULT '0' COMMENT '删除标志（0-正常 1-删除）',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_item_name` (`item_name`),
  KEY `idx_group_status` (`group_name`, `status`, `del_flag`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='影像检查白话词典（患者端影像报告解读的规则层地基，人工维护）';

