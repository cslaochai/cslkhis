package com.his.system.enums;

/**
 * 字段值打码方式。
 *
 * <p><b>口径：只打"直接标识符"。</b>
 * 身份证 / 手机号 / 银行卡·卡号这类能一把定位到自然人的字段必打码；
 * 姓名、性别、住址、过敏史、状态这些业务字段<b>不打码</b> ——
 * 全打码的审计日志等于没有日志，检查时问"这个患者性别什么时候被改的"你答不上来。
 *
 * <p>为什么连日志都要打码：日志表的可见面比主档宽（只读不写、常被导出给检查人员），
 * 不打码等于给"能看日志的人"开了一条绕过主档权限拿全量身份证的路。
 */
public enum MaskEnum {

    /** 不打码（业务字段默认） */
    NONE,

    /** 身份证号：前 6 后 4，中间全星 —— 行政区划+出生日期段保留便于核对，顺序码和校验位遮掉 */
    ID_CARD,

    /** 手机号：11 位取前 3 后 4；其它长度取前 2 后 2 */
    PHONE,

    /** 银行卡号 / 医保卡号 / 其它证件号：前 4 后 4 */
    BANK_NO,

    /** 姓名：留姓，其余打星 */
    NAME,

    /** 住址：留前 6 个字（够认出是哪个小区片区），后面全星 */
    ADDRESS
}
